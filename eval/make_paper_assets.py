#!/usr/bin/env python3
"""Build the paper's evaluation table and figure from the results files.

Writes ``../figures/eval-models.pdf`` (dumbbell chart, baseline to four-turn,
one panel per metric) and ``../eval-table.tex`` (one row per model). Every
number in the paper's evaluation section comes from here, so it cannot drift
from ``eval/``. No model calls.

    python eval/make_paper_assets.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent

# Display name, results location, vendor, note. Order: full coverage first.
MODELS = [
    ("Claude Haiku 4.5", None, "Anthropic"),
    ("GPT-5.6 Luna", "openai__gpt-5.6-luna", "OpenAI"),
    ("Qwen3.8 Flash", "qwen__qwen3.8-flash", "Alibaba"),
    ("Llama 4 Maverick", "meta-llama__llama-4-maverick", "Meta"),
    ("Gemini 3.1 Flash-Lite", "gemini-3.1-flash-lite", "Google"),
    ("DeepSeek Flash", "deepseek-flash", "DeepSeek"),
    ("Claude Sonnet 5", "claude-sonnet-5", "Anthropic"),
]
BLUE, INK, MUTED, GRID = "#2a78d6", "#0b0b0b", "#52514e", "#e6e5e1"


def programs(path: Path) -> dict:
    data = json.loads(path.read_text())
    return {p["slug"]: p for p in data.get("results", data)["programs"]}


def load(model_dir):
    if model_dir is None:
        return programs(HERE / "baseline.json"), programs(HERE / "four-turn.json")
    base = HERE / "models" / model_dir
    return programs(base / "baseline" / "results.json"), programs(base / "four-turn" / "results.json")


def mean(progs, slugs, fn):
    vals = [fn(progs[s]) for s in slugs if not progs[s].get("error")]
    return sum(vals) / len(vals) if vals else float("nan")


def passed(progs, slugs):
    return sum(1 for s in slugs if (progs[s].get("end_to_end") or {}).get("passed"))


def summarise():
    haiku_four = load(None)[1]
    rows = []
    for name, model_dir, vendor in MODELS:
        base, four = load(model_dir)
        slugs = sorted(set(base) & set(four))
        n = len(slugs)
        row = {"name": name, "vendor": vendor, "n": n}
        for tag, progs in (("b", base), ("f", four)):
            row[f"steps_{tag}"] = mean(progs, slugs, lambda p: p["steps"]["f1"])
            row[f"rel_{tag}"] = mean(progs, slugs, lambda p: p["relationships"]["f1"])
            row[f"unsup_{tag}"] = mean(progs, slugs, lambda p: p["unsupported_rate"])
            row[f"e2e_{tag}"] = passed(progs, slugs)
            row[f"noprog_{tag}"] = sum(1 for s in slugs if progs[s].get("error") and "no JSON" in str(progs[s]["error"]))
        row["cost_f"] = sum(four[s]["extras"]["cost_usd"] for s in slugs) / n
        row["tok_f"] = sum(four[s]["extras"]["output_tokens"] for s in slugs) / n
        row["haiku_same"] = passed(haiku_four, slugs)
        rows.append(row)
    return rows


def table(rows) -> str:
    out = [
        "% Generated by eval/make_paper_assets.py. Do not edit by hand.",
        r"\begin{tabular}{@{}l r cc cc cc r r r@{}}",
        r"\toprule",
        r" & & \multicolumn{2}{c}{Steps F1} & \multicolumn{2}{c}{Relationships F1} & \multicolumn{2}{c}{End to end} & Haiku & Cost & Output \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
        r"Model & $n$ & base & 4-turn & base & 4-turn & base & 4-turn & same $n$ & (\$) & tokens \\",
        r"\midrule",
    ]
    for r in rows:
        out.append(
            f"{r['name']} & {r['n']} & {r['steps_b']:.2f} & {r['steps_f']:.2f} & {r['rel_b']:.2f} & {r['rel_f']:.2f} & "
            f"{r['e2e_b']} & {r['e2e_f']} & {r['haiku_same']} & {r['cost_f']:.3f} & {r['tok_f'] / 1000:.1f}k \\\\"
        )
    out += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(out)


def figure(rows, path: Path) -> None:
    plt.rcParams.update({"font.family": "Helvetica", "font.size": 8, "pdf.fonttype": 42})
    panels = [
        ("Steps F1", "steps_b", "steps_f", lambda r, k: r[k]),
        ("Relationships F1", "rel_b", "rel_f", lambda r, k: r[k]),
        ("End-to-end pass rate", "e2e_b", "e2e_f", lambda r, k: r[k] / r["n"]),
    ]
    fig, axes = plt.subplots(1, 3, figsize=(7.0, 2.55), sharey=True)
    ys = list(range(len(rows)))[::-1]
    for ax, (title, kb, kf, get) in zip(axes, panels):
        for y, r in zip(ys, rows):
            b, f = get(r, kb), get(r, kf)
            ax.plot([b, f], [y, y], color="#b9b8b3", lw=1.6, zorder=1, solid_capstyle="round")
            ax.scatter([b], [y], s=34, facecolor="white", edgecolor=BLUE, linewidth=1.6, zorder=3)
            ax.scatter([f], [y], s=34, facecolor=BLUE, edgecolor="white", linewidth=0.8, zorder=4)
            ax.annotate(f"{f:.2f}", (f, y), xytext=(6, 0), textcoords="offset points", va="center", fontsize=7, color=INK)
        ax.set_title(title, fontsize=8.5, color=INK, loc="left", pad=6)
        ax.set_xlim(0, 1.12)
        ax.set_xticks([0, 0.25, 0.5, 0.75, 1.0])
        ax.set_xticklabels(["0", "", "0.5", "", "1"])
        ax.set_ylim(-0.7, len(rows) - 0.3)
        ax.grid(axis="x", color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color("#c9c8c3")
        ax.tick_params(axis="both", length=0, colors=MUTED)
    axes[0].set_yticks(ys)
    axes[0].set_yticklabels([f"{r['name']}  (n={r['n']})" for r in rows], color=INK)
    handles = [
        plt.Line2D([], [], marker="o", ls="", markersize=6, markerfacecolor="white", markeredgecolor=BLUE, markeredgewidth=1.6, label="single-shot baseline"),
        plt.Line2D([], [], marker="o", ls="", markersize=6, markerfacecolor=BLUE, markeredgecolor="white", label="four-turn prompt"),
    ]
    fig.legend(handles=handles, loc="lower center", ncol=2, frameon=False, fontsize=8, bbox_to_anchor=(0.56, -0.02), handletextpad=0.3, columnspacing=2.0)
    fig.subplots_adjust(left=0.235, right=0.985, top=0.88, bottom=0.2, wspace=0.12)
    fig.savefig(path)
    fig.savefig(path.with_suffix(".png"), dpi=200)
    plt.close(fig)


def main() -> None:
    rows = summarise()
    (PAPER / "eval-table.tex").write_text(table(rows))
    figure(rows, PAPER / "figures" / "eval-models.pdf")
    for r in rows:
        print(f"{r['name']:22} n={r['n']:2}  steps {r['steps_b']:.2f}->{r['steps_f']:.2f}  rel {r['rel_b']:.2f}->{r['rel_f']:.2f}  "
              f"unsup {100*r['unsup_b']:.0f}%->{100*r['unsup_f']:.0f}%  e2e {r['e2e_b']}->{r['e2e_f']}/{r['n']} (haiku same n: {r['haiku_same']})  "
              f"no-program {r['noprog_b']}/{r['noprog_f']}  ${r['cost_f']:.3f}  {r['tok_f']:.0f} tok")


if __name__ == "__main__":
    main()
